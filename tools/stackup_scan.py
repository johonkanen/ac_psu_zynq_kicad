"""Impedance of a fixed trace width on every layer of JLC 8-layer stack-ups, for a given layer-role map.

python3 tools/stackup_scan.py [--w 0.102] [--gap 0.102] FILE.kicad_pcb ...
FILE: KiCad stack-up templates (e.g. gsuberland/jlcpcb_autogenerated_stackups, `kicad_stackups/jlcpcb_8L_*`).

Layer roles are juliancoy/zynqPCB's (PLAN.md §4.3): planes on In1, In3, In5; signals on F, In2, In4, In6, B. In6 is taken
as a stripline between In5 and B (B carries pours under the DDR in the source; if it does not, In6 is closer to a
microstrip and the impedance is higher). A signal trace sits on the core side of its layer and is embedded in the
prepreg. Uses tools/zsolve.py (2D field solve)."""
import argparse, re, sys
from zsolve import z_se, z_diff

ap = argparse.ArgumentParser()
ap.add_argument("files", nargs="+")
ap.add_argument("--w", type=float, default=0.102)
ap.add_argument("--gap", type=float, default=0.102, help="edge-to-edge gap of the differential pairs")
ap.add_argument("--h", type=float, default=0.0025, help="solver grid (mm)")
a = ap.parse_args()

PLANES = {"In1.Cu", "In3.Cu", "In5.Cu", "B.Cu"}   # B is a reference only for In6
SIGNALS = ["F.Cu", "In2.Cu", "In4.Cu", "In6.Cu"]
ER_MASK = 3.8

def stack(path):
    t = open(path, errors="ignore").read()
    t = t[t.index("(stackup"):t.index("(copper_finish")]
    out = []
    for m in re.finditer(r'\(layer "([^"]+)"\s*\(type "([^"]+)"\)(.*?)\n\t\t\t\)', t, re.S):
        name, typ, body = m.groups()
        th = re.search(r"\(thickness ([\d.]+)", body); er = re.search(r"\(epsilon_r ([\d.]+)", body)
        out.append(dict(name=name, type=typ, t=float(th.group(1)) if th else 0.0, er=float(er.group(1)) if er else None))
    return [x for x in out if x["type"] in ("copper", "core", "prepreg")]

def tr(ws, g, y0, y1):
    if g is None:
        return [(-ws / 2, ws / 2, y0, y1, 1.0)]
    c = g / 2 + ws / 2
    return [(-c - ws / 2, -c + ws / 2, y0, y1, 1.0), (c - ws / 2, c + ws / 2, y0, y1, -1.0)]

def geom(st, sig, w, g):
    i = [k for k, x in enumerate(st) if x["name"] == sig][0]
    tc = st[i]["t"]
    if sig == "F.Cu":            # microstrip on the prepreg to In1, with mask
        hp, er = st[i + 1]["t"], st[i + 1]["er"]
        t = tr(w, g, hp, hp + tc)
        sl = [(0, hp, er), (hp, hp + 0.015, ER_MASK)]
        sl += [(hp, hp + tc + 0.015, ER_MASK, x0 - 0.015, x1 + 0.015) for x0, x1, *_ in t]   # mask over the copper
        return dict(stack=sl, planes=[0], traces=t, top_open=True, width=3.0, h=a.h)
    up, dn = st[i - 1], st[i + 1]            # dielectrics above and below
    assert st[i - 2]["name"] in PLANES and st[i + 2]["name"] in PLANES, (sig, st[i - 2]["name"], st[i + 2]["name"])
    core, pp = (dn, up) if dn["type"] == "core" else (up, dn)
    # y = 0 at the plane on the core side; core, then the trace on it, embedded in the prepreg up to the other plane
    top = core["t"] + pp["t"]
    t = tr(w, g, core["t"], core["t"] + tc)
    return dict(stack=[(0, core["t"], core["er"]), (core["t"], top, pp["er"])], planes=[0, top], traces=t,
                top_open=False, width=3.0, h=a.h)

print(f"# w = {a.w} mm SE, pairs {a.w}/{a.gap} mm; targets 40 ohm SE / 80 ohm diff (UG933, +/-10 %: 36-44 / 72-88)")
for f in a.files:
    st = stack(f)
    name = re.search(r"(JLC0\w+-\w+)", f).group(1)
    thick = sum(x["t"] for x in st)
    row = []
    for s in SIGNALS:
        zs, ee = z_se(**geom(st, s, a.w, None))
        zd, _ = z_diff(**geom(st, s, a.w, a.gap))
        row.append(f"{s[:-3]:3} {zs:5.1f}/{zd:5.1f} ({3.33564 * ee ** 0.5:.2f} ps/mm)")
    print(f"{name:18} {thick:5.3f} mm  " + "  ".join(row), flush=True)
