#!/usr/bin/env python3
"""Stack-up, layer roles, net classes and DRC rules for kicad/zynq_card (run after tools/make_board.py).

Ported from the Ti135 card (efinix_soc_board/tools/board_setup.py); the values are this card's.
- Layer user names (LAYER_NAMES): 1.Top, 2.GND, 3.Sig, 4.GND, 5.Sig, 6.GND, 7.Sig, 8.Bottom.
- Stack-up: **JLC081611-7628** (1.593 mm, 1 oz inner; ZYNQ_PCB_NOTES.md §6.4), written from STACKUP below. The values
  are JLC's, as in gsuberland/jlcpcb_autogenerated_stackups `jlcpcb_8L_1.6mm_outer1oz_inner1oz_JLC081611-7628`.
  Layer roles are juliancoy's (PLAN.md §4.3): GND planes on In1/In3/In5 (KiCad type "power"), signals on
  F/In2/In4/In6, B.Cu for pours, power and parts.
- Net classes (kicad/zynq_card.kicad_pro): the block's DDR3 geometry (0.102/0.102 mm, 0.48/0.25 mm vias: what
  juliancoy routed, 39.5-45.5 ohm on the inner layers), the MIO interfaces (0.1 mm inner, about 40 ohm), the MDI pairs
  (0.35/0.20 mm on F.Cu = 102 ohm), power.
- Design rules (kicad/zynq_card.kicad_dru): JLC 8-layer minimums in the project, DDR3 widths and MDI geometry in the
  rule file. Inside the block (rule area `ddr3_block`, drawn by tools/import_block.py) the copied copper is checked
  only against the minimums: it is never re-widthed (PLAN.md §4.3).
Plain python3 (s-expression edit of the saved board).
"""
import json
import os
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
sys.path.insert(0, os.path.join(TOOLS, "p2k"))
from p2k.sexpr import Sym, find, load, save  # noqa: E402

PCB = os.environ.get("P2K_PCB", os.path.join(ROOT, "kicad", "zynq_card.kicad_pcb"))   # the stack-up goes here
PRO = os.path.join(ROOT, "kicad", "zynq_card.kicad_pro")
DRU = os.path.join(ROOT, "kicad", "zynq_card.kicad_dru")

# KiCad "power" = plane layer. F.Cu S | In1 GND | In2 S | In3 GND | In4 S | In5 GND | In6 S | B.Cu S
LAYER_TYPES = {"F.Cu": "signal", "In1.Cu": "power", "In2.Cu": "signal", "In3.Cu": "power", "In4.Cu": "signal",
               "In5.Cu": "power", "In6.Cu": "signal", "B.Cu": "signal"}
# user names shown in KiCad (items and rules keep the standard names; scripts that print or match layer names use
# BOARD.GetStandardLayerName)
LAYER_NAMES = {"F.Cu": "1.Top", "In1.Cu": "2.GND", "In2.Cu": "3.Sig", "In3.Cu": "4.GND", "In4.Cu": "5.Sig",
               "In5.Cu": "6.GND", "In6.Cu": "7.Sig", "B.Cu": "8.Bottom"}

# JLC081611-7628, top to bottom: (layer, type, thickness mm, material, epsilon_r)
P7628, P1080, CORE = "Nan Ya Plastics NP-155F 7628 x2", "Nan Ya Plastics NP-155F 1080 x2", "Nan Ya Plastics NP-155F Core"
STACKUP = [
    ("F.Cu", "copper", 0.035), ("dielectric 1", "prepreg", 0.421, P7628, 4.4),
    ("In1.Cu", "copper", 0.030), ("dielectric 2", "core", 0.075, CORE, 3.99),
    ("In2.Cu", "copper", 0.030), ("dielectric 3", "prepreg", 0.138, P1080, 3.91),
    ("In3.Cu", "copper", 0.030), ("dielectric 4", "core", 0.075, CORE, 3.99),
    ("In4.Cu", "copper", 0.030), ("dielectric 5", "prepreg", 0.138, P1080, 3.91),
    ("In5.Cu", "copper", 0.030), ("dielectric 6", "core", 0.075, CORE, 3.99),
    ("In6.Cu", "copper", 0.030), ("dielectric 7", "prepreg", 0.421, P7628, 4.4),
    ("B.Cu", "copper", 0.035),
]
MASK = (0.01524, "JLCPCB Soldermask", 3.8)


def stackup_node():
    st = [Sym("stackup"),
          [Sym("layer"), "F.SilkS", [Sym("type"), "Top Silk Screen"]],
          [Sym("layer"), "F.Paste", [Sym("type"), "Top Solder Paste"]],
          [Sym("layer"), "F.Mask", [Sym("type"), "Top Solder Mask"], [Sym("thickness"), MASK[0]],
           [Sym("material"), MASK[1]], [Sym("epsilon_r"), MASK[2]], [Sym("loss_tangent"), 0]]]
    for name, typ, th, *diel in STACKUP:
        node = [Sym("layer"), name, [Sym("type"), typ]]
        if typ != "copper":
            node.append([Sym("color"), "FR4 natural"])
        node.append([Sym("thickness"), th])
        if diel:
            node += [[Sym("material"), diel[0]], [Sym("epsilon_r"), diel[1]], [Sym("loss_tangent"), 0.02]]
        st.append(node)
    st += [[Sym("layer"), "B.Mask", [Sym("type"), "Bottom Solder Mask"], [Sym("thickness"), MASK[0]],
            [Sym("material"), MASK[1]], [Sym("epsilon_r"), MASK[2]], [Sym("loss_tangent"), 0]],
           [Sym("layer"), "B.Paste", [Sym("type"), "Bottom Solder Paste"]],
           [Sym("layer"), "B.SilkS", [Sym("type"), "Bottom Silk Screen"]],
           [Sym("copper_finish"), "ENIG"], [Sym("dielectric_constraints"), Sym("no")]]
    return st


def stackup():
    total = sum(s[2] for s in STACKUP) + 2 * MASK[0]
    assert abs(sum(s[2] for s in STACKUP) - 1.593) < 0.001, "JLC081611-7628 is 1.593 mm without mask"
    ours = load(PCB)
    for entry in find(ours, "layers")[1:]:
        if isinstance(entry, list) and len(entry) > 2 and str(entry[1]) in LAYER_TYPES:
            entry[2] = Sym(LAYER_TYPES[str(entry[1])])
            del entry[3:]
            entry.append(LAYER_NAMES[str(entry[1])])
    find(find(ours, "general"), "thickness")[1] = round(total, 4)
    setup = find(ours, "setup")
    old = find(setup, "stackup")
    if old is not None:
        setup[setup.index(old)] = stackup_node()
    else:
        setup.insert(1, stackup_node())
    save(PCB, ours)


NETCLASSES = [
    # name, track, clearance, via, via drill, diff width, diff gap
    ("Default", 0.1, 0.1, 0.48, 0.25, 0.1, 0.2),
    # the block's geometry (juliancoy: 0.102 mm everywhere, all vias 0.48/0.25 through)
    ("ddr3", 0.102, 0.1, 0.48, 0.25, 0.102, 0.102),
    ("ddr3_diff", 0.102, 0.1, 0.48, 0.25, 0.102, 0.102),
    # RGMII, SD0 (eMMC), QSPI: 0.1 mm inner = about 40 ohm (§6.4); skew limits only
    ("mio_fast", 0.1, 0.1, 0.48, 0.25, 0.1, 0.2),
    # MDI: 0.35/0.20 mm on F.Cu = 102 ohm (§6.4)
    # (class clearance 0.1: the PHY's QFN pads are on 0.4 mm pitch; the 0.2 mm track spacing is a rule)
    ("mdi", 0.35, 0.1, 0.48, 0.25, 0.35, 0.2),
    ("PWR", 0.3, 0.1, 0.48, 0.25, 0.1, 0.2),
    ("PWR_CORE", 0.5, 0.1, 0.48, 0.25, 0.1, 0.2),
]
PATTERNS = [
    ("ddr3", r"^DDR3_(A[0-9]+|BA[0-2]|DQ[0-9]+|DM[0-3]|CKE|ODT|RAS#|CAS#|WE#|CS#|DRST#)$"),
    ("ddr3_diff", r"^DDR3_(DQS[0-3]|CK)_[PN]$"),
    ("mio_fast", r"^/(rgmii_(txc|tx_ctl|txd[0-3]|rxc|rx_ctl|rxd[0-3])|sd_(clk|cmd|dat[0-3])|qspi_(sclk|cs_n|io[0-3]))$"),
    ("mio_fast", r"^/09 ethernet/phy_(txc|tx_ctl|txd[0-3]|rxc|rx_ctl|rxd[0-3])$"),
    ("mio_fast", r"^/10 emmc/emmc_clk$"),
    ("mdi", r"^/09 ethernet/eth_mdi_[a-d]_[PN]$"),
    ("PWR", r"^(1V8|1V35|3V3|3V3_analog|DDR3_VTT)$"),
    ("PWR", r"^/05 soc_power/(VCCPLL|VCCAUX)$"),
    ("PWR", r"^/09 ethernet/phy_(avdd33|vdd10|dvdd_rg)$"),
    ("PWR_CORE", r"^(1V0|5V0)$"),
]


def netclasses():
    pro = json.load(open(PRO))
    ns = pro.setdefault("net_settings", {})
    tmpl = (ns.get("classes") or [{}])[0]
    classes = []
    for name, tw, cl, via, drill, dpw, dpg in NETCLASSES:
        c = dict(tmpl)
        c.update({"name": name, "track_width": tw, "clearance": cl, "via_diameter": via, "via_drill": drill,
                  "diff_pair_width": dpw, "diff_pair_gap": dpg, "microvia_diameter": 0.2, "microvia_drill": 0.1,
                  "tuning_profile": "", "priority": len(classes) if name != "Default" else 2147483647})
        classes.append(c)
    ns["classes"] = classes
    ns["netclass_patterns"] = [{"netclass": c, "pattern": p} for c, p in PATTERNS]
    rules = pro.setdefault("board", {}).setdefault("design_settings", {}).setdefault("rules", {})
    # JLC multilayer: 0.09 mm trace/space (3.5 mil), 0.2 mm via drill, 0.45 mm via pad; [verify at quote time]
    # for 1 oz inner copper (STATUS.md open items). The block needs 0.102/0.102 and 0.48/0.25.
    rules.update({"min_clearance": 0.09, "min_track_width": 0.09, "min_via_diameter": 0.45,
                  "min_via_annular_width": 0.1, "min_through_hole_diameter": 0.2, "min_hole_clearance": 0.2,
                  "min_hole_to_hole": 0.25, "min_copper_edge_clearance": 0.5, "min_silk_clearance": 0.0,
                  "min_text_height": 0.8, "min_text_thickness": 0.15, "use_height_for_length_calcs": True})
    json.dump(pro, open(PRO, "w"), indent=2)


DRU_TEXT = """(version 1)
# Zynq control card DRC rules (written by tools/board_setup.py; do not edit by hand).
# KiCad applies the LAST matching rule. JLC minimums are in the project (board_setup.py netclasses()).
# Stack-up JLC081611-7628 (ZYNQ_PCB_NOTES.md §6.4): 0.102 mm = 39.5 ohm on In2/In4, 45.5 ohm on In6, 111 ohm on F.Cu.

# ---- DDR3 outside the block: the block's geometry ---------------------------------------------------
# Inside the rule area 'ddr3_block' (tools/import_block.py) the copied copper keeps juliancoy's widths (PLAN.md §4.3).
(rule "ddr3_width"
	(condition "(A.hasNetclass('ddr3') || A.hasNetclass('ddr3_diff')) && !A.intersectsArea('ddr3_block')")
	(constraint track_width (min 0.09mm) (opt 0.102mm) (max 0.115mm)))
(rule "ddr3_diff_gap"
	(condition "A.hasNetclass('ddr3_diff') && !A.intersectsArea('ddr3_block')")
	(constraint diff_pair_gap (min 0.09mm) (opt 0.102mm) (max 0.15mm)))

# ---- MDI pairs: F.Cu only, 0.35/0.20 mm = 102 ohm (NASR-M erratum: inner-layer MDI was worse) -------
(rule "mdi_geometry"
	(condition "A.hasNetclass('mdi') && A.Layer == 'F.Cu'")
	(constraint track_width (min 0.33mm) (opt 0.35mm) (max 0.37mm))
	(constraint diff_pair_gap (min 0.18mm) (opt 0.2mm) (max 0.22mm)))
(rule "mdi_spacing"
	(condition "A.Type == 'Track' && A.hasNetclass('mdi') && A.NetName != B.NetName && !B.inDiffPair('*')")
	(constraint clearance (min 0.2mm)))
(rule "mdi_layers"
	(condition "A.Type == 'Track' && A.hasNetclass('mdi') && A.Layer != 'F.Cu'")
	(constraint disallow track))

# ---- MIO interfaces: no width below 0.09 mm, keep them off the outer layers outside the escapes -------
(rule "mio_fast_width"
	(condition "A.hasNetclass('mio_fast')")
	(constraint track_width (min 0.09mm) (opt 0.1mm) (max 0.2mm)))

# J3 corner pins 37/38: the hole positions come from the Ti60 card / baseboard (MECHANICAL.md) and sit
# 0.89 mm from the top edge, so their pads are 0.39 mm from it. JLC's routed-edge minimum is 0.3 mm.
(rule "j3_baseboard_edge"
	(condition "A.memberOfFootprint('J3')")
	(constraint edge_clearance (min 0.3mm)))
"""


def dru():
    open(DRU, "w").write(DRU_TEXT)


if __name__ == "__main__":
    stackup()
    netclasses()
    dru()
    print("board_setup: stack-up JLC081611-7628 + layer roles, net classes, DRC rules written")
