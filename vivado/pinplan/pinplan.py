"""Zynq-7000 pin plan for the control card: assign the PL signals to balls, build a Vivado project with the PS7
configured (DDR3L x32, QSPI, GEM0 RGMII, SD0 eMMC, UART1, I2C0, both MIO banks at 1.8 V), run synthesis and placement,
and write the checked pin plan.

    python3 vivado/pinplan/pinplan.py [--vivado ~/Xilinx/2024.2/Vivado/2024.2]

Inputs (this folder): signals.csv (PL signals, direction, group), groups.csv (group -> bank), mio.csv (MIO use, for the
schematic), ps7.tcl (PS7 settings). Outputs: zynq_pinplan.csv (signal -> ball), ps7_mio.csv (MIO pins as Vivado
configured them), and build/ (the Vivado project and reports, git-ignored).

The ball choice inside a bank is a first pass: balls are taken from the package edge inwards, clock-capable (MRCC/SRCC)
and VREF balls are kept free, and PUDC_B is never used (it is tied to VCCO_34, ZYNQ_PCB_NOTES.md §5). The order is
re-done once the parts are placed (pin swaps inside a bank are free), as with the Ti135 pin-plan loop."""
import argparse, csv, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(HERE, "build")
PART = "xc7z020clg484-1"
ROWS = list("ABCDEFGHJKLMNPRTUVWY") + ["AA", "AB"]

ap = argparse.ArgumentParser()
ap.add_argument("--vivado", default=os.path.expanduser("~/Xilinx/2024.2/Vivado/2024.2"))
a = ap.parse_args()

def vivado(tcl, log):
    env_cmd = f'source "{a.vivado}/settings64.sh" >/dev/null 2>&1 && vivado -mode batch -nojournal -log "{log}" -source "{tcl}"'
    r = subprocess.run(["bash", "-c", env_cmd], cwd=BUILD, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"vivado failed ({tcl}), see {log}:\n" + "\n".join(l for l in r.stdout.splitlines() if "ERROR" in l))

def rc(ball):
    m = re.match(r"([A-Z]+)(\d+)$", ball)
    return ROWS.index(m.group(1)), int(m.group(2))

os.makedirs(BUILD, exist_ok=True)

# 1. package pins from Vivado itself
pkg = os.path.join(BUILD, "pkgpins.csv")
if not os.path.exists(pkg):
    with open(os.path.join(BUILD, "dump_pkg.tcl"), "w") as f:
        f.write(f"""link_design -part {PART}
set f [open pkgpins.csv w]
puts $f "pin,bank,func,min_delay_ps,max_delay_ps"
foreach p [get_package_pins] {{ puts $f "[get_property NAME $p],[get_property BANK $p],[get_property PIN_FUNC $p],[get_property MIN_DELAY $p],[get_property MAX_DELAY $p]" }}
close $f
""")
    vivado("dump_pkg.tcl", "dump_pkg.log")
pins = list(csv.DictReader(open(pkg)))

# 2. assign
sigs = list(csv.DictReader(open(os.path.join(HERE, "signals.csv"))))
banks = {r["group"]: r["bank"] for r in csv.DictReader(open(os.path.join(HERE, "groups.csv")))}
free = {}
for p in pins:
    fn = p["func"]
    if not fn.startswith("IO_") or re.search(r"PUDC|VREF|MRCC|SRCC", fn):
        continue
    free.setdefault(p["bank"], []).append(p)
for b, lst in free.items():   # package edge first: the outermost column/row of the bank, then inwards
    rs = [rc(p["pin"]) for p in lst]
    cmax = max(c for _, c in rs); rmax = max(r for r, _ in rs)
    edge_right = cmax == 22
    lst.sort(key=lambda p: ((22 - rc(p["pin"])[1]) if edge_right else (len(ROWS) - 1 - rc(p["pin"])[0]),
                            rc(p["pin"])))
assign = {}
for s in sigs:
    b = banks[s["group"]]
    if not free.get(b):
        sys.exit(f"bank {b} is full ({s['signal']})")
    p = free[b].pop(0)
    assign[s["signal"]] = (p["pin"], b, p["func"])

# 3. top level, constraints, build script
ports = ",\n".join(f"    {'output' if s['dir'] == 'out' else 'input '} wire {s['signal']}" for s in sigs)
outs = [s["signal"] for s in sigs if s["dir"] == "out"]
ins = [s["signal"] for s in sigs if s["dir"] == "in"]
body = "\n".join(f"  assign {o} = cnt[{i % 24 + 8}] ^ in_x;" for i, o in enumerate(outs))
with open(os.path.join(BUILD, "top.v"), "w") as f:
    f.write(f"""// generated by pinplan.py: PS7 + every PL pin, with just enough logic to keep the ports
module top (
    inout  wire [14:0] DDR_addr, inout wire [2:0] DDR_ba, inout wire DDR_cas_n, inout wire DDR_ck_n,
    inout  wire DDR_ck_p, inout wire DDR_cke, inout wire DDR_cs_n, inout wire [3:0] DDR_dm,
    inout  wire [31:0] DDR_dq, inout wire [3:0] DDR_dqs_n, inout wire [3:0] DDR_dqs_p, inout wire DDR_odt,
    inout  wire DDR_ras_n, inout wire DDR_reset_n, inout wire DDR_we_n,
    inout  wire FIXED_IO_ddr_vrn, inout wire FIXED_IO_ddr_vrp, inout wire [53:0] FIXED_IO_mio,
    inout  wire FIXED_IO_ps_clk, inout wire FIXED_IO_ps_porb, inout wire FIXED_IO_ps_srstb,
{ports}
);
  wire clk;
  ps_wrapper ps_i (.DDR_addr(DDR_addr), .DDR_ba(DDR_ba), .DDR_cas_n(DDR_cas_n), .DDR_ck_n(DDR_ck_n),
    .DDR_ck_p(DDR_ck_p), .DDR_cke(DDR_cke), .DDR_cs_n(DDR_cs_n), .DDR_dm(DDR_dm), .DDR_dq(DDR_dq),
    .DDR_dqs_n(DDR_dqs_n), .DDR_dqs_p(DDR_dqs_p), .DDR_odt(DDR_odt), .DDR_ras_n(DDR_ras_n),
    .DDR_reset_n(DDR_reset_n), .DDR_we_n(DDR_we_n), .FIXED_IO_ddr_vrn(FIXED_IO_ddr_vrn),
    .FIXED_IO_ddr_vrp(FIXED_IO_ddr_vrp), .FIXED_IO_mio(FIXED_IO_mio), .FIXED_IO_ps_clk(FIXED_IO_ps_clk),
    .FIXED_IO_ps_porb(FIXED_IO_ps_porb), .FIXED_IO_ps_srstb(FIXED_IO_ps_srstb), .FCLK_CLK0(clk));
  reg [31:0] cnt = 0;
  reg [{len(ins) - 1}:0] in_s = 0;
  always @(posedge clk) begin cnt <= cnt + 1; in_s <= {{{", ".join(ins)}}}; end
  wire in_x = ^in_s;
{body}
endmodule
""")
with open(os.path.join(BUILD, "pins.xdc"), "w") as f:
    f.write("# generated by pinplan.py\n")
    for s in sigs:
        ball = assign[s["signal"]][0]
        f.write(f"set_property -dict {{PACKAGE_PIN {ball} IOSTANDARD LVCMOS33}} [get_ports {s['signal']}]\n")
    f.write("set_property CFGBVS VCCO [current_design]\nset_property CONFIG_VOLTAGE 3.3 [current_design]\n")
with open(os.path.join(BUILD, "build.tcl"), "w") as f:
    f.write(f"""create_project -force pinplan . -part {PART}
create_bd_design ps
set ps [create_bd_cell -type ip -vlnv xilinx.com:ip:processing_system7 ps7]
source {os.path.join(HERE, "ps7.tcl")}
set_property -dict $PS7_CONFIG $ps
apply_bd_automation -rule xilinx.com:bd_rule:processing_system7 -config {{make_external "FIXED_IO, DDR" Master "Disable" Slave "Disable"}} $ps
create_bd_port -dir O -type clk FCLK_CLK0
connect_bd_net [get_bd_pins ps7/FCLK_CLK0] [get_bd_ports FCLK_CLK0]
validate_bd_design
save_bd_design
set f [open ps7_config.txt w]
foreach p [lsort [list_property $ps CONFIG.*]] {{ puts $f "$p = [get_property $p $ps]" }}
close $f
set_property synth_checkpoint_mode None [get_files ps.bd]
generate_target all [get_files ps.bd]
add_files -norecurse [make_wrapper -files [get_files ps.bd] -top] top.v
add_files -fileset constrs_1 pins.xdc
set_property top top [current_fileset]
synth_design -top top -part {PART}
opt_design
place_design
write_checkpoint -force placed.dcp
report_drc -file drc.rpt
report_io -file io.rpt
report_utilization -file util.rpt
set f [open placed_pins.csv w]
puts $f "port,ball,bank,iostandard,direction"
foreach p [get_ports] {{ puts $f "[get_property NAME $p],[get_property PACKAGE_PIN $p],[get_property IOBANK $p],[get_property IOSTANDARD $p],[get_property DIRECTION $p]" }}
close $f
""")

# 4. Vivado: PS7 + synth + place + DRC
vivado("build.tcl", "build.log")

# 5. results
placed = {r["port"]: r for r in csv.DictReader(open(os.path.join(BUILD, "placed_pins.csv")))}
bad = [s["signal"] for s in sigs if placed.get(s["signal"], {}).get("ball") != assign[s["signal"]][0]]
drc = open(os.path.join(BUILD, "drc.rpt")).read()
m = re.search(r"Checks found:\s*(\d+)", drc)
errs = re.findall(r"^\| (\S+)\s+\| (Error|Critical Warning)\s+\|", drc, re.M)
with open(os.path.join(HERE, "zynq_pinplan.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["signal", "dir", "ball", "bank", "pin_function", "iostandard", "group", "note"])
    for s in sigs:
        ball, b, fn = assign[s["signal"]]
        w.writerow([s["signal"], s["dir"], ball, b, fn, placed[s["signal"]]["iostandard"], s["group"], s["note"]])
cfg = dict(l.split(" = ", 1) for l in open(os.path.join(BUILD, "ps7_config.txt")).read().splitlines() if " = " in l)
with open(os.path.join(HERE, "ps7_mio.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["mio", "peripheral", "iotype", "direction", "pullup", "slew"])
    for i in range(54):
        k = f"CONFIG.PCW_MIO_{i}_"
        w.writerow([i, cfg.get(f"CONFIG.PCW_MIO_TREE_PERIPHERALS", "").split("#")[i] if "#" in cfg.get("CONFIG.PCW_MIO_TREE_PERIPHERALS", "") else "",
                    cfg.get(k + "IOTYPE", ""), cfg.get(k + "DIRECTION", ""), cfg.get(k + "PULLUP", ""), cfg.get(k + "SLEW", "")])
print(f"{len(sigs)} PL signals placed; mismatches vs plan: {bad or 'none'}")
print("banks used:", {b: sum(1 for v in assign.values() if v[1] == b) for b in sorted({v[1] for v in assign.values()})},
      "free user I/O left:", {b: len(v) for b, v in sorted(free.items())})
crit = sorted({l.split("]")[0] + "]" for l in open(os.path.join(BUILD, "build.log")) if l.startswith("CRITICAL WARNING")})
print(f"DRC (placed design): {m.group(1) if m else '?'} violations {sorted(set(errs)) or ''}; critical warnings in the build: {crit or 'none'}")
for k in ("PCW_UIPARAM_DDR_PARTNO", "PCW_UIPARAM_DDR_BUS_WIDTH", "PCW_UIPARAM_DDR_MEMORY_TYPE", "PCW_UIPARAM_DDR_FREQ_MHZ",
          "PCW_PRESET_BANK0_VOLTAGE", "PCW_PRESET_BANK1_VOLTAGE", "PCW_APU_PERIPHERAL_FREQMHZ",
          *[f"PCW_UIPARAM_DDR_DQS_TO_CLK_DELAY_{i}" for i in range(4)], *[f"PCW_UIPARAM_DDR_BOARD_DELAY{i}" for i in range(4)],
          *[f"PCW_PACKAGE_DDR_DQS_TO_CLK_DELAY_{i}" for i in range(4)], *[f"PCW_PACKAGE_DDR_BOARD_DELAY{i}" for i in range(4)]):
    print(f"  {k} = {cfg.get('CONFIG.' + k)}")
